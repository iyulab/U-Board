// What the board language takes from the widget library's catalog: each widget's name, category, one-line
// description and option names. Read once from the library and written to `widget-catalog.generated.ts`, so the
// board-v2 entry reaches no package at runtime — a server or MCP process can validate a board without the widget
// library installed beside it, and which kinds exist is fixed by this package's release, not by whichever library
// version a process happens to resolve. A test compares the written copy with the installed library.

/** One widget of the library, as the board language reads it. */
export interface WidgetCatalogEntry {
  widget: string;
  category: string;
  description: string;
  /** The option names the widget takes, in the library's order. */
  options: string[];
}

/** The two functions of the library's `./tools` entry this reads. */
export interface WidgetLibraryTools {
  help(): unknown;
  getWidgetOptions(widget: string): readonly { key: string }[] | null | undefined;
}

/** The catalog as the library reports it now. */
export function readWidgetCatalog(tools: WidgetLibraryTools): WidgetCatalogEntry[] {
  const catalog = tools.help() as { widget: string; category: string; description: string }[];
  return catalog.map(({ widget, category, description }) => ({
    widget,
    category,
    description,
    options: (tools.getWidgetOptions(widget) ?? []).map(o => o.key),
  }));
}

/** The source of `widget-catalog.generated.ts` for a catalog. */
export function widgetCatalogModule(catalog: readonly WidgetCatalogEntry[], libraryVersion: string): string {
  return [
    '// Generated by `npm run gen:widget-catalog` from @iyulab/u-widgets ' + libraryVersion + ' — do not edit by hand.',
    '',
    "import type { WidgetCatalogEntry } from './widget-catalog.js';",
    '',
    'export const WIDGET_CATALOG: readonly WidgetCatalogEntry[] = ' + JSON.stringify(catalog, null, 2) + ';',
    '',
  ].join('\n');
}
